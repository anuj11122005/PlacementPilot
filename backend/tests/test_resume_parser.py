class TestUnsupportedExtension:
    def test_txt_file_raises_parsing_error(self, tmp_path: Path) -> None:
        txt_file = tmp_path / "resume.txt"
        txt_file.write_text("Some resume content", encoding="utf-8")
        with pytest.raises(ParsingError, match="[Uu]nsupported"):
            parse_resume(txt_file)

    def test_nonexistent_file_raises_parsing_error(self, tmp_path: Path) -> None:
        with pytest.raises(ParsingError, match="[Nn]ot found"):
            parse_resume(tmp_path / "ghost.pdf")
