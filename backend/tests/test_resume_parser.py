class TestValidPDF:
    def test_valid_pdf_returns_string(self) -> None:
        assert_fixture_exists("valid_resume.pdf")
        result = parse_resume(fixture("valid_resume.pdf"))
        assert isinstance(result, str)

    def test_valid_pdf_returns_nonempty_text(self) -> None:
        assert_fixture_exists("valid_resume.pdf")
        result = parse_resume(fixture("valid_resume.pdf"))
        assert len(result.strip()) > 0

    def test_valid_pdf_contains_expected_content(self) -> None:
        """The fixture PDF contains 'Skills' — verify extraction works."""
        assert_fixture_exists("valid_resume.pdf")
        result = parse_resume(fixture("valid_resume.pdf"))
        # At least some recognisable content should come through
        assert any(
            word.lower() in result.lower()
            for word in ["skills", "python", "experience", "education"]
        ), f"Expected recognizable resume content in output, got: {result[:200]!r}"


